package uao.edu.co.scouts_project.member.shared.enums;

/**
 * Enumeración que representa los diferentes tipos de documentos
 * de identificación válidos dentro del sistema Scouts.
 * <p>
 * Cada valor corresponde a una sigla oficial utilizada en Colombia
 * para identificar personas naturales o jurídicas.
 */
public enum DocumentType {

    /** Cédula de Ciudadanía */
    CC,

    /** Tarjeta de Identidad */
    TI,

    /** Registro Civil */
    RC,

    /** Cédula de Extranjería */
    CE,

    /** Pasaporte */
    PA,

    /** Permiso Especial de Permanencia */
    PEP,

    /** Permiso por Protección Temporal */
    PPT,

    /** Número de Identificación Tributaria */
    NIT,

    /** Número Único de Identificación Personal */
    NUIP
}